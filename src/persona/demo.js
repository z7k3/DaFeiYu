function pick(list, rng) {
  const r = typeof rng === 'function' ? rng() : Math.random();
  return list[Math.min(list.length - 1, Math.floor(r * list.length))];
}

function mockReply({ text, userName = '你', chatType = 'private', notes = [], rng = Math.random }) {
  const raw = String(text || '').trim();
  const isGroup = chatType === 'group';
  const rule = MOCK_RULES.find((r) => r.test.test(raw));
  let reply;
  if (rule) reply = pick(isGroup ? rule.group : rule.private, rng);
  else if (notes.length && /记得|记住|我叫|叫我/.test(raw)) reply = `记住啦，${notes[0]}，人家不会忘的 (｡•̀ᴗ-)✧`;
  else if (/\?|？|吗|呢|怎么|为什么|多少/.test(raw)) {
    const q = ['唔…这个问题，其实答案是"看情况"啦。你再跟我讲讲具体是哪种情况？', '让本鲸想想…你先说说你现在最想解决哪一步？', '这个嘛，人家的第一个念头是"别急，先试试看"，你觉得呢？'];
    reply = pick(isGroup ? ['这个我也好奇', '等个答案，我也想知道'] : q, rng);
  } else reply = pick(isGroup ? MOCK_FALLBACKS_GROUP : MOCK_FALLBACKS_PRIVATE, rng);
  if (!isGroup && userName && userName !== '你' && !reply.includes(userName) && rng() < 0.18) reply = `${userName}，${reply}`;
  return reply;
}

